export function pickMessage(type: ChickMessageType): string {
  const pool = MESSAGE_POOL[type]
  if (!pool || pool.length === 0) {
    return ''
  }
  const idx = Math.floor(Math.random() * pool.length)
  return pool[idx] ?? ''
}
